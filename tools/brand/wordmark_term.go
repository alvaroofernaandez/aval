package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"strconv"
	"strings"
)

// The terminal wordmark (DESIGN.md section 10, "### Wordmark"): a raster of
// wordPrims, the same geometry as the SVG wordmark. Port of the approved
// prototype odd/tasks/tui-hub-wordmark-prototype.py, "quad:7:word".
const (
	termRows      = 7    // text rows of the Unicode tier
	termSS        = 4    // samples per pixel edge (4x4 supersampling)
	termThreshold = 0.42 // coverage at which a pixel is ink
	termCellRatio = 2.05 // terminal cell height over width
)

// quadrant maps (top-left, top-right, bottom-left, bottom-right) to a block.
var quadrant = map[[4]bool]string{
	{false, false, false, false}: " ", {true, false, false, false}: "▘",
	{false, true, false, false}: "▝", {false, false, true, false}: "▖",
	{false, false, false, true}: "▗", {true, true, false, false}: "▀",
	{false, false, true, true}: "▄", {true, false, true, false}: "▌",
	{false, true, false, true}: "▐", {true, false, false, true}: "▚",
	{false, true, true, false}: "▞", {true, true, true, false}: "▛",
	{true, true, false, true}: "▜", {true, false, true, true}: "▙",
	{false, true, true, true}: "▟", {true, true, true, true}: "█",
}

// inked reports whether (px, py) lies under any stroke of width sw. segDist
// (hero.go) blocks fused multiply-add, so the result matches the prototype.
func inked(prims []prim, sw, px, py float64) bool {
	for _, p := range prims {
		if p.circle {
			if math.Abs(math.Hypot(px-p.pts[0][0], py-p.pts[0][1])-p.r) <= sw/2 {
				return true
			}
			continue
		}
		for i := 1; i < len(p.pts); i++ {
			if segDist(px, py, p.pts[i-1][0], p.pts[i-1][1], p.pts[i][0], p.pts[i][1]) <= sw/2 {
				return true
			}
		}
	}
	return false
}

// box is the sampled area of the wordmark in brand units.
type box struct{ x0, y0, x1, y1 float64 }

// raster samples prims over b into cols x rows pixels; a pixel is ink when at
// least termThreshold of its termSS x termSS samples are.
func raster(prims []prim, sw float64, b box, cols, rows int) [][]bool {
	g := make([][]bool, rows)
	for j := range g {
		g[j] = make([]bool, cols)
		for i := range g[j] {
			c := 0
			for a := 0; a < termSS; a++ {
				for s := 0; s < termSS; s++ {
					px := b.x0 + (float64(i)+(float64(a)+.5)/termSS)*(b.x1-b.x0)/float64(cols)
					py := b.y0 + (float64(j)+(float64(s)+.5)/termSS)*(b.y1-b.y0)/float64(rows)
					if inked(prims, sw, px, py) {
						c++
					}
				}
			}
			g[j][i] = float64(c)/(termSS*termSS) >= termThreshold
		}
	}
	return g
}

// termWordmark returns the Unicode tier (quadrant blocks) and the ASCII tier
// (# at half resolution, one pixel per cell). Rows are right-trimmed and then
// padded to a common width.
func termWordmark() (unicode, ascii []string) {
	prims, w := wordPrims(0, wordASC)
	b := box{-wordS / 2, 0, w + wordS/2, wordASC}
	aspect := (b.x1 - b.x0) / (b.y1 - b.y0)
	cols := int(math.RoundToEven(termRows * aspect * termCellRatio))

	q := raster(prims, wordS, b, cols*2, termRows*2)
	for r := 0; r < termRows; r++ {
		var line strings.Builder
		for c := 0; c < cols; c++ {
			line.WriteString(quadrant[[4]bool{q[2*r][2*c], q[2*r][2*c+1], q[2*r+1][2*c], q[2*r+1][2*c+1]}])
		}
		unicode = append(unicode, line.String())
	}

	h := raster(prims, wordS, b, cols, termRows)
	for _, row := range h {
		var line strings.Builder
		for _, on := range row {
			if on {
				line.WriteByte('#')
			} else {
				line.WriteByte(' ')
			}
		}
		ascii = append(ascii, line.String())
	}
	return evenRows(unicode), evenRows(ascii)
}

// evenRows trims trailing blanks, then pads every row to the widest.
func evenRows(rows []string) []string {
	width := 0
	for i, r := range rows {
		rows[i] = strings.TrimRight(r, " ")
		width = max(width, len([]rune(rows[i])))
	}
	for i, r := range rows {
		rows[i] = r + strings.Repeat(" ", width-len([]rune(r)))
	}
	return rows
}

// wordmarkTermSource renders internal/ui/wordmark_gen.go.
func wordmarkTermSource() []byte {
	uni, asc := termWordmark()
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/brand; DO NOT EDIT.\n\n")
	b.WriteString("package ui\n\n")
	fmt.Fprintf(&b, "// wordmarkUnicode is the wordmark in quadrant blocks: %d rows, %dx%d samples\n", termRows, termSS, termSS)
	fmt.Fprintf(&b, "// per subpixel at %.2f coverage.\n", termThreshold)
	writeRows(&b, "wordmarkUnicode", uni)
	b.WriteString("\n// wordmarkASCII is the same raster in # at half resolution.\n")
	writeRows(&b, "wordmarkASCII", asc)
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err) // the template above is fixed; a failure is a bug here
	}
	return out
}

func writeRows(b *bytes.Buffer, name string, rows []string) {
	fmt.Fprintf(b, "var %s = []string{\n", name)
	for _, r := range rows {
		fmt.Fprintf(b, "\t%s,\n", strconv.Quote(r))
	}
	b.WriteString("}\n")
}
