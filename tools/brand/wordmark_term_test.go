package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func wordmarkGenPath(t *testing.T) string {
	t.Helper()
	return filepath.Join(filepath.Dir(repoDocs(t)), "internal", "ui", "wordmark_gen.go")
}

// The committed internal/ui/wordmark_gen.go is what the generator emits now.
func TestWordmarkGenIsCurrent(t *testing.T) {
	want := wordmarkTermSource()
	got, err := os.ReadFile(wordmarkGenPath(t))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("internal/ui/wordmark_gen.go is stale; run: go run ./tools/brand --wordmark-term internal/ui/wordmark_gen.go\n--- want ---\n%s", want)
	}
}

func TestWordmarkGenHeader(t *testing.T) {
	src := string(wordmarkTermSource())
	if !strings.HasPrefix(src, "// Code generated by tools/brand; DO NOT EDIT.\n") {
		t.Fatalf("missing generated-code header:\n%s", src)
	}
	for _, v := range []string{"var wordmarkUnicode = []string{", "var wordmarkASCII = []string{"} {
		if !strings.Contains(src, v) {
			t.Errorf("missing %q", v)
		}
	}
}

func TestWordmarkTermFlagWritesFile(t *testing.T) {
	out := filepath.Join(t.TempDir(), "wordmark_gen.go")
	var so, se bytes.Buffer
	if err := run([]string{"--wordmark-term", out}, &so, &se); err != nil {
		t.Fatal(err, se.String())
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if want := wordmarkTermSource(); len(want) == 0 || !bytes.Equal(got, want) {
		t.Fatalf("flag output differs from wordmarkTermSource:\n%s", got)
	}
}

// The rasteriser and the SVG draw the same primitives: the SVG wordmark is
// built from wordPrims, so the raster cannot drift from the published logo.
func TestWordmarkPrimsDriveSVG(t *testing.T) {
	prims, w := wordPrims(0, wordASC)
	if len(prims) != 6 {
		t.Fatalf("want 6 primitives (ring and stem per a, the check polyline, the l), got %d", len(prims))
	}
	elems, w2 := wordPaths(0, wordASC)
	if w != w2 || len(elems) != 6 {
		t.Fatalf("width %v vs %v, %d svg elements", w, w2, len(elems))
	}
}
