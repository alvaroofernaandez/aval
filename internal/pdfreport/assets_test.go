func writePNG(t *testing.T, path string, w, h int, px func(x, y int) color.NRGBA) {
	t.Helper()
	img := image.NewNRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.SetNRGBA(x, y, px(x, y))
		}
	}
	var b bytes.Buffer
	if err := png.Encode(&b, img); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

func writeJPG(t *testing.T, path string, w, h int) {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, color.RGBA{200, 120, 80, 255})
		}
	}
	var b bytes.Buffer
	if err := jpeg.Encode(&b, img, nil); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

const fontCSS = `/* cyrillic */
@font-face {
  font-family: 'Fraunces';
  font-style: normal;
  font-weight: 400;
  src: url(https://fonts.example/cyr.woff2) format('woff2');
  unicode-range: U+0400-045F;
}
/* latin-ext */
@font-face {
  font-family: 'Fraunces';
  font-style: normal;
  font-weight: 400;
  src: url(https://fonts.example/ext.woff2) format('woff2');
  unicode-range: U+0100-02AF;
}
/* latin */
@font-face {
  font-family: 'Fraunces';
  font-style: italic;
  font-weight: 700;
  src: url(https://fonts.example/lat.woff2) format('woff2');
  unicode-range: U+0000-00FF;
}
`

func fakeGet(missingIcon string) func(url, ua string) ([]byte, error) {
	return func(url, ua string) ([]byte, error) {
		switch {
		case strings.HasPrefix(url, "https://fonts.googleapis.com/css2?family="):
			if ua == "" {
				return nil, errors.New("Google Fonts needs a browser User-Agent")
			}
			return []byte(fontCSS), nil
		case strings.HasPrefix(url, "https://fonts.example/"):
			return []byte("WOFF2:" + strings.TrimPrefix(url, "https://fonts.example/")), nil
		case strings.Contains(url, "/icons/"):
			name := strings.TrimSuffix(url[strings.LastIndex(url, "/")+1:], ".svg")
			if name == missingIcon {
				return nil, errors.New("404")
			}
			return []byte("<!-- lucide -->\n<svg stroke=\"currentColor\"><path d=\"" + name + "\"/></svg>\n"), nil
		}
		return nil, errors.New("unexpected url " + url)
	}
}

func decodeVar(t *testing.T, css, name string) (mime string, raw []byte) {
	t.Helper()
	m := regexp.MustCompile(`--` + regexp.QuoteMeta(name) + `: url\(data:([^;]+);base64,([^)]+)\)`).FindStringSubmatch(css)
	if m == nil {
		t.Fatalf("no --%s in css", name)
	}
	raw, err := base64.StdEncoding.DecodeString(m[2])
	if err != nil {
		t.Fatal(err)
	}
	return m[1], raw
}

func brandDir(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	// A white disc with a transparent corner, so alpha has to survive.
	writePNG(t, filepath.Join(dir, "logo.png"), 64, 64, func(x, y int) color.NRGBA {
		dx, dy := float64(x)-31.5, float64(y)-31.5
		if dx*dx+dy*dy < 28*28 {
			return color.NRGBA{255, 255, 255, 255}
		}
		return color.NRGBA{}
	})
	writePNG(t, filepath.Join(dir, "banner.png"), 100, 50, func(x, y int) color.NRGBA { return color.NRGBA{10, 20, 30, 255} })
	writeJPG(t, filepath.Join(dir, "ana.jpg"), 120, 200)
	return dir
}

func TestBuildAssets(t *testing.T) {
	brand := brandDir(t)
	proj := t.TempDir()
	var out bytes.Buffer
	err := Assets(AssetOptions{
		Project: proj, BrandDir: brand, LogoFile: "logo.png",
		People: []string{"ana", "luis"}, Ink: [3]uint8{23, 20, 31}, Accent: [3]uint8{110, 59, 106},
		Get: fakeGet("ban"), Out: &out,
	})
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(proj, "assets", "brand.css"))
	if err != nil {
		t.Fatal(err)
	}
	css := string(b)

	if !strings.HasPrefix(css, "/* Generated by `aval pdf assets`. Do not edit by hand. */") {
		t.Errorf("header: %q", css[:60])
	}
	if strings.Contains(css, "cyrillic") || strings.Contains(css, "cyr.woff2") {
		t.Error("an unwanted unicode subset was embedded")
	}
	for _, want := range []string{"/* Fraunces · latin-ext */", "/* Fraunces · latin */", "unicode-range: U+0100-02AF;", "font-style: italic;", "font-weight: 700;", "font-display: block;"} {
		if !strings.Contains(css, want) {
			t.Errorf("css lacks %q", want)
		}
	}
	_, raw := decodeVar(t, css, "ic-clock")
	if s := string(raw); strings.Contains(s, "currentColor") || strings.Contains(s, "<!--") || !strings.Contains(s, `stroke="#000"`) {
		t.Errorf("icon not made mask-ready: %q", s)
	}
	if !strings.Contains(css, ".ico-clock { -webkit-mask-image: var(--ic-clock); mask-image: var(--ic-clock); }") {
		t.Error("no .ico-clock class")
	}
	if strings.Contains(css, ".ico-ban ") || strings.Contains(css, "--ic-ban:") {
		t.Error("a missing icon still got a class")
	}
	if !strings.Contains(out.String(), "MISSING ICONS: ban") || !strings.Contains(out.String(), "portrait not found, skipping: luis") {
		t.Errorf("summary: %s", out.String())
	}
	if !strings.Contains(out.String(), "brand.css") || !strings.Contains(out.String(), "5 images") {
		t.Errorf("summary lacks counts (3 logos, banner, 1 portrait): %s", out.String())
	}

	// Logo colourways keep the alpha silhouette and swap the colour.
	mime, raw := decodeVar(t, css, "img-logo-ink")
	img, err := png.Decode(bytes.NewReader(raw))
	if err != nil || mime != "image/png" {
		t.Fatalf("logo-ink: %v %s", err, mime)
	}
	if img.Bounds().Dx() != 256 || img.Bounds().Dy() != 256 {
		t.Errorf("logo size %v", img.Bounds())
	}
	if c := color.NRGBAModel.Convert(img.At(128, 128)).(color.NRGBA); c != (color.NRGBA{23, 20, 31, 255}) {
		t.Errorf("logo-ink centre %v", c)
	}
	if c := color.NRGBAModel.Convert(img.At(0, 0)).(color.NRGBA); c.A != 0 {
		t.Errorf("logo-ink corner not transparent: %v", c)
	}
	_, raw = decodeVar(t, css, "img-logo-white")
	img, _ = png.Decode(bytes.NewReader(raw))
	if c := color.NRGBAModel.Convert(img.At(128, 128)).(color.NRGBA); c.R < 250 || c.G < 250 || c.B < 250 {
		t.Errorf("logo-white centre %v", c)
	}

	// Banner is a 1200x300 JPEG.
	mime, raw = decodeVar(t, css, "img-banner")
	jb, err := jpeg.Decode(bytes.NewReader(raw))
	if err != nil || mime != "image/jpeg" || jb.Bounds().Dx() != 1200 || jb.Bounds().Dy() != 300 {
		t.Fatalf("banner: %v %s %v", err, mime, jb)
	}

	// Portrait: circular, 340px, corners transparent, centre opaque.
	_, raw = decodeVar(t, css, "img-photo-ana")
	p, err := png.Decode(bytes.NewReader(raw))
	if err != nil || p.Bounds().Dx() != 340 || p.Bounds().Dy() != 340 {
		t.Fatalf("portrait: %v %v", err, p.Bounds())
	}
	if _, _, _, a := p.At(2, 2).RGBA(); a != 0 {
		t.Errorf("portrait corner alpha %d, want 0", a)
	}
	if _, _, _, a := p.At(170, 170).RGBA(); a>>8 != 255 {
		t.Errorf("portrait centre alpha %d, want 255", a>>8)
	}
	if c := color.NRGBAModel.Convert(p.At(170, 4)).(color.NRGBA); c.A == 0 {
		t.Errorf("portrait ring missing: %v", c)
	}
}

func TestBuildAssetsErrors(t *testing.T) {
	err := Assets(AssetOptions{Project: t.TempDir(), BrandDir: filepath.Join(t.TempDir(), "nope"), LogoFile: "logo.png", Get: fakeGet(""), Out: &bytes.Buffer{}})
	if err == nil || !strings.Contains(err.Error(), "Brand image directory not found") {
		t.Errorf("missing brand dir: %v", err)
	}
	empty := t.TempDir()
	err = Assets(AssetOptions{Project: t.TempDir(), BrandDir: empty, LogoFile: "logo.png", Get: fakeGet(""), Out: &bytes.Buffer{}})
	if err == nil {
		t.Error("a brand dir without logo must fail")
	}
}

func TestParseRGB(t *testing.T) {
	if c, err := ParseRGB("23,20,31"); err != nil || c != [3]uint8{23, 20, 31} {
		t.Errorf("%v %v", c, err)
	}
	for _, bad := range []string{"1,2", "1,2,3,4", "a,b,c", "1,2,256", "-1,2,3"} {
		if _, err := ParseRGB(bad); err == nil {
			t.Errorf("ParseRGB(%q) accepted", bad)
		}
	}
}
