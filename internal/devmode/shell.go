package devmode

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ShellSpec is how to start an interactive shell inside a sandbox: the program,
// its arguments, extra environment, and the rc files to write first (path to
// content). It is pure data so every platform branch can be tested anywhere.
type ShellSpec struct {
	Path  string
	Args  []string
	Env   []string
	Files map[string]string
}

// Marker is the prompt prefix that tells you which sandbox a shell belongs to.
// Names are validated, so it is safe to embed in any shell's quoting.
func Marker(name string) string { return "[aval dev:" + name + "]" }

// Shell picks the user's shell and arranges for the prompt to carry the marker.
// On Windows $SHELL is ignored: PowerShell (pwsh, then Windows PowerShell),
// else cmd. Elsewhere $SHELL, falling back to sh.
func Shell(s Sandbox, goos, shellEnv string, look func(string) (string, error)) ShellSpec {
	mk := Marker(s.Name)

	if goos == "windows" {
		for _, ps := range []string{"pwsh", "powershell"} {
			if p, err := look(ps); err == nil {
				return ShellSpec{Path: p, Args: []string{
					"-NoLogo", "-NoExit", "-Command",
					"function global:prompt { '" + mk + " PS ' + $PWD.Path + '> ' }",
				}}
			}
		}
		return ShellSpec{Path: "cmd.exe", Args: []string{"/K", "prompt " + mk + "$P$G"}}
	}

	path := shellEnv
	if path == "" {
		if p, err := look("sh"); err == nil {
			path = p
		} else {
			path = "sh"
		}
	}

	switch strings.TrimSuffix(filepath.Base(path), ".exe") {
	case "zsh":
		rc := filepath.Join(s.RC(), ".zshrc")
		return ShellSpec{Path: path, Args: []string{"-i"}, Files: map[string]string{rc: zshRC(mk)}}
	case "bash":
		rc := filepath.Join(s.RC(), "bashrc")
		return ShellSpec{Path: path, Args: []string{"--rcfile", rc, "-i"}, Files: map[string]string{rc: bashRC(mk)}}
	default:
		return ShellSpec{Path: path, Env: []string{"PS1=" + mk + " $ "}}
	}
}

func zshRC(mk string) string {
	return `# generated by aval dev; recreated on every entry
[ -r "$HOME/.zshrc" ] && source "$HOME/.zshrc"
_aval_dev_marker() {
  case "$PROMPT" in
    *'` + mk + `'*) ;;
    *) PROMPT="%F{214}` + mk + `%f $PROMPT" ;;
  esac
}
autoload -Uz add-zsh-hook
add-zsh-hook precmd _aval_dev_marker
_aval_dev_marker
`
}

func bashRC(mk string) string {
	return `# generated by aval dev; recreated on every entry
[ -r "$HOME/.bashrc" ] && . "$HOME/.bashrc"
PS1="` + mk + ` ${PS1}"
`
}

// WriteFiles writes the rc files of a ShellSpec. Callers pass only specs built
// for a verified sandbox, so every path is under its root.
func WriteFiles(root string, files map[string]string) error {
	for p, content := range files {
		if !inside(root, p) {
			return fmt.Errorf("refusing to write %s outside the sandbox", p)
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}
