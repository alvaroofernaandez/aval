// Guards against publishing an employer's material from a personal dotfiles
// repo. The skills under shared/skills are the risk surface: prose accumulates
// the pricing matrix, client names and demo credentials that gitleaks cannot
// see. Two scopes are checked; the history one matters, because deleting files
// leaves every earlier commit intact.

// proprietaryPatterns come from the Go binary, assembled from fragments there
// (internal/prepush): a scanner whose source spells the words it forbids
// matches itself.
func proprietaryPatterns(t *testing.T) []*regexp.Regexp {
	t.Helper()
	r := run(repo, nil, "", avalBin(t), "hook", "pre-push", "patterns")
	var out []*regexp.Regexp
	for _, l := range strings.Split(r.Stdout, "\n") {
		if l = strings.TrimSpace(l); l != "" {
			out = append(out, regexp.MustCompile("(?i)"+l))
		}
	}
	isTrue(t, "the patterns come from the Go binary (>= 10)", len(out) >= 10)
	return out
}

// scanTree returns "file:line" hits for every pattern across files.
func scanTree(pats []*regexp.Regexp, root string, files []string) []string {
	var hits []string
	for _, f := range files {
		b, err := os.ReadFile(root + "/" + f)
		if err != nil || bytes.IndexByte(b, 0) >= 0 { // unreadable or binary
			continue
		}
		for i, line := range strings.Split(string(b), "\n") {
			for _, re := range pats {
				if re.MatchString(line) {
					hits = append(hits, f+":"+strconv.Itoa(i+1))
				}
			}
		}
	}
	return hits
}

// trackedAndUntracked lists what git would commit: tracked files plus
// untracked ones that are not ignored.
func trackedAndUntracked(t *testing.T) []string {
	t.Helper()
	needGit(t)
	r := run(repo, nil, "", "git", "ls-files", "-co", "--exclude-standard")
	var out []string
	for _, f := range strings.Split(r.Stdout, "\n") {
		if f != "" && exists(p(f)) {
			out = append(out, f)
		}
	}
	return out
}

func TestNoProprietaryMaterialInTheWorkingTree(t *testing.T) {
	pats := proprietaryPatterns(t)
	if hits := scanTree(pats, repo, trackedAndUntracked(t)); len(hits) > 0 {
		t.Errorf("proprietary material in the working tree:\n  %s", strings.Join(hits, "\n  "))
	}
}

func TestNoProprietaryMaterialInAnyCommit(t *testing.T) {
	t.Parallel()
	pats := proprietaryPatterns(t)
	needGit(t)
	slow(t)

	cmd := exec.Command("git", "log", "--all", "-p", "--no-color")
	cmd.Dir = repo
	out, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	hits := 0
	sc := bufio.NewScanner(out)
	sc.Buffer(make([]byte, 1<<20), 64<<20)
	for sc.Scan() {
		l := sc.Text()
		if !strings.HasPrefix(l, "+") {
			continue
		}
		for _, re := range pats {
			if re.MatchString(l) {
				hits++
			}
		}
	}
	_ = cmd.Wait()
	eq(t, "added lines carrying proprietary material", 0, hits)
}

// Deleting the skills would pass both scans while destroying the tooling.
func TestNoProprietaryGenericSkillsReplacedTheDeletedOnes(t *testing.T) {
	for _, skill := range []string{"pdf-report", "repo-prep"} {
		isTrue(t, "the generic "+skill+" skill exists", exists(p("shared/skills", skill, "SKILL.md")))
	}
}

// A skill that reads generic but defaults to a brand directory under $HOME.
func TestNoProprietaryNoDefaultBrandDirectoryUnderHome(t *testing.T) {
	src := read(t, "internal/pdfreport/assets.go") // missing file fails, not passes
	mustNotHave(t, `UserHomeDir|Getenv\("HOME"\)`, src, "assets.go must not default to a brand dir under $HOME")
}

// .atl/skill-registry.md is regenerated by scanning $HOME, so it lists private
// and client skills and rewrites itself on every refresh. It has to stay
// untracked, not merely clean.
func TestNoProprietaryMachineWideSkillIndexIsNotTracked(t *testing.T) {
	needGit(t)
	r := run(repo, nil, "", "git", "ls-files", ".atl/*")
	eq(t, "tracked files under .atl/", "", strings.TrimSpace(r.Stdout))
	c := run(repo, nil, "", "git", "check-ignore", "-q", ".atl/skill-registry.md")
	eq(t, ".atl/ is ignored (git check-ignore exit)", 0, c.Code)
}

// A scanner that cannot be shown to catch anything is decoration.
func TestNoProprietaryPlantedMaterialIsDetected(t *testing.T) {
	pats := proprietaryPatterns(t)
	dir := t.TempDir()
	first := strings.TrimPrefix(pats[0].String(), "(?i)")
	write(t, dir+"/planted.md", "client: "+first+".es\ncreds: "+"pass"+"word123\n")
	hits := scanTree(pats, dir, []string{"planted.md"})
	isTrue(t, "planted proprietary material is detected on >= 2 lines", len(hits) >= 2)
}
